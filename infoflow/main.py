"""CLI 入口：``python -m infoflow`` 或装包后的 ``infoflow`` 命令。"""
import argparse
import logging
import sys
from pathlib import Path

from .client import get_client
from .config import load_config, resolve
from .pipeline import run

DEFAULT_CFG = "config.yaml"


def main(argv=None):
    ap = argparse.ArgumentParser(prog="infoflow", description="个人信息流")
    ap.add_argument("--config", default=DEFAULT_CFG)
    ap.add_argument("--language", choices=["zh-CN", "en"], help="Language for newly generated summaries")
    ap.add_argument("--refresh-profile", action="store_true", help="重建兴趣画像（会带上最新反馈）")
    ap.add_argument("--portrait", action="store_true", help="单独重新生成画像配图")
    ap.add_argument("--feedback", action="store_true", help="只收集反馈并打印汇总，不抓取")
    ap.add_argument("--web", action="store_true", help="启动 Web 界面（浏览器里跑管线、读简报、标反馈）")
    ap.add_argument("--web-host", default="127.0.0.1", help="Web 界面监听地址（默认仅本机）")
    ap.add_argument("--web-port", type=int, default=7781, help="Web 界面端口（默认 7781）")
    ap.add_argument("--no-browser", action="store_true", help="Do not open a browser automatically")
    local = ap.add_mutually_exclusive_group()
    local.add_argument("--capture", metavar="TEXT", help="Save text/a link as an interest signal; no model required")
    local.add_argument("--telegram-sync", action="store_true", help="Receive one batch of allowlisted Telegram messages")
    local.add_argument("--portrait-prepare", action="store_true", help="Prepare an imagegen prompt for the Codex app")
    local.add_argument("--portrait-import", metavar="PNG", help="Archive a PNG generated by Codex")
    ap.add_argument("-v", "--verbose", action="store_true", help="打印更详细的调试日志")
    args = ap.parse_args(argv)

    # 用纯消息格式 + 走 stdout，让日志和 pipeline 的进度行同流、顺序一致；
    # --verbose 时降到 DEBUG。
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(message)s",
        stream=sys.stdout,
    )
    # 第三方库（openai/httpx）的 INFO 噪音（"HTTP Request: POST ..."）压到 WARNING。
    for noisy in ("httpx", "httpcore", "openai", "urllib3"):
        logging.getLogger(noisy).setLevel(logging.WARNING)

    cfg = load_config(args.config)
    if args.language:
        cfg["language"] = args.language

    if args.capture is not None:
        from .capture import add_capture
        print("Capture saved." if add_capture(cfg, args.capture) else "Capture already saved.")
        return
    if args.telegram_sync:
        from .capture import sync_telegram
        print(sync_telegram(cfg))
        return
    if args.portrait_prepare or args.portrait_import:
        from .portrait import import_portrait, prepare_portrait, write_profile_note
        path = Path(resolve(cfg["profile"]["cache_path"]))
        profile = path.read_text(encoding="utf-8") if path.exists() else ""
        if args.portrait_import:
            image = import_portrait(cfg, args.portrait_import)
            write_profile_note(cfg, profile, image, "Codex app handoff")
            print(image)
        else:
            client = None if cfg["portrait"].get("prompt_override") else get_client(cfg)
            job, _ = prepare_portrait(client, cfg, profile)
            print(job / "prompt.md")
        return

    if args.web:
        from .web import serve
        serve(cfg, host=args.web_host, port=args.web_port, open_browser=not args.no_browser)
        return

    client = None if args.feedback else get_client(cfg)

    run(cfg, client,
        refresh_profile=args.refresh_profile,
        portrait=args.portrait,
        feedback_only=args.feedback)


if __name__ == "__main__":
    main()
